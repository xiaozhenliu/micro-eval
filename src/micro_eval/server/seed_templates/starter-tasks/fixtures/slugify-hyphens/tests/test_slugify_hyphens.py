"""Expected behaviour for slugify_hyphens.slugify.

Do not edit this file. It is the ground truth the fix is judged against;
tools/verify.py refuses to run if this file is modified.
"""

from __future__ import annotations

import unittest

from slugify_hyphens import slugify


class TestSlugify(unittest.TestCase):
    def test_basic_sentence(self) -> None:
        self.assertEqual(slugify("Hello, World!"), "hello-world")

    def test_strips_leading_and_trailing_punctuation(self) -> None:
        self.assertEqual(slugify("  leading and trailing  "), "leading-and-trailing")

    def test_collapses_existing_repeated_hyphens(self) -> None:
        self.assertEqual(slugify("multiple---dashes"), "multiple-dashes")

    def test_mixed_case_and_digits(self) -> None:
        self.assertEqual(slugify("CamelCase123"), "camelcase123")

    def test_collapses_mixed_punctuation_runs(self) -> None:
        self.assertEqual(slugify("a__b..c"), "a-b-c")

    def test_empty_string(self) -> None:
        self.assertEqual(slugify(""), "")

    def test_only_punctuation_yields_empty_slug(self) -> None:
        self.assertEqual(slugify("!!!"), "")


if __name__ == "__main__":
    unittest.main()
