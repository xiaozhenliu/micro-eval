from __future__ import annotations

import unittest

from csv_quoted_fields import parse_csv_line


class TestParseCsvLine(unittest.TestCase):
    def test_simple_unquoted_fields(self) -> None:
        self.assertEqual(parse_csv_line("a,b,c"), ["a", "b", "c"])

    def test_quoted_field_with_comma(self) -> None:
        self.assertEqual(parse_csv_line('"a,b",c'), ["a,b", "c"])

    def test_quoted_field_with_escaped_quote(self) -> None:
        self.assertEqual(parse_csv_line('"a""b",c'), ['a"b', "c"])

    def test_empty_fields_are_preserved(self) -> None:
        self.assertEqual(parse_csv_line("a,,c"), ["a", "", "c"])

    def test_trailing_quoted_field(self) -> None:
        self.assertEqual(parse_csv_line('a,"b"'), ["a", "b"])

    def test_whole_line_quoted_with_no_comma(self) -> None:
        self.assertEqual(parse_csv_line('"hello"'), ["hello"])

    def test_multiple_quoted_fields_with_commas(self) -> None:
        self.assertEqual(parse_csv_line('"a,1","b,2",c'), ["a,1", "b,2", "c"])


if __name__ == "__main__":
    unittest.main()
