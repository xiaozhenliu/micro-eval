from __future__ import annotations

import unittest

from page_bounds import page_bounds


class TestPageBounds(unittest.TestCase):
    def test_first_page(self) -> None:
        self.assertEqual(page_bounds(25, 10, 1), (0, 10))

    def test_middle_page(self) -> None:
        self.assertEqual(page_bounds(25, 10, 2), (10, 20))

    def test_last_partial_page_clamps_end(self) -> None:
        self.assertEqual(page_bounds(25, 10, 3), (20, 25))

    def test_page_beyond_range_clamps_to_total(self) -> None:
        self.assertEqual(page_bounds(25, 10, 4), (25, 25))

    def test_empty_collection(self) -> None:
        self.assertEqual(page_bounds(0, 10, 1), (0, 0))

    def test_exact_multiple_of_page_size(self) -> None:
        self.assertEqual(page_bounds(20, 10, 2), (10, 20))

    def test_invalid_page_size_raises(self) -> None:
        with self.assertRaises(ValueError):
            page_bounds(25, 0, 1)

    def test_invalid_page_number_raises(self) -> None:
        with self.assertRaises(ValueError):
            page_bounds(25, 10, 0)


if __name__ == "__main__":
    unittest.main()
