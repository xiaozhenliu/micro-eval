from __future__ import annotations

import unittest

from lru_cache_order import LRUCache


class TestLRUCache(unittest.TestCase):
    def test_basic_put_get(self) -> None:
        cache = LRUCache(2)
        cache.put("a", 1)
        self.assertEqual(cache.get("a"), 1)

    def test_missing_key_returns_none(self) -> None:
        cache = LRUCache(2)
        self.assertIsNone(cache.get("missing"))

    def test_evicts_least_recently_used_on_overflow(self) -> None:
        cache = LRUCache(2)
        cache.put("a", 1)
        cache.put("b", 2)
        cache.put("c", 3)  # capacity 2: "a" was inserted first, evicted.
        self.assertIsNone(cache.get("a"))
        self.assertEqual(cache.get("b"), 2)
        self.assertEqual(cache.get("c"), 3)

    def test_get_refreshes_recency(self) -> None:
        cache = LRUCache(2)
        cache.put(1, "a")
        cache.put(2, "b")
        cache.get(1)  # touch 1, so 2 becomes the least recently used.
        cache.put(3, "c")  # must evict 2, not 1.
        self.assertIsNone(cache.get(2))
        self.assertEqual(cache.get(1), "a")
        self.assertEqual(cache.get(3), "c")

    def test_put_existing_key_updates_value_without_growing(self) -> None:
        cache = LRUCache(2)
        cache.put("a", 1)
        cache.put("a", 2)
        self.assertEqual(cache.get("a"), 2)

    def test_capacity_one_evicts_previous_key(self) -> None:
        cache = LRUCache(1)
        cache.put("a", 1)
        cache.put("b", 2)
        self.assertIsNone(cache.get("a"))
        self.assertEqual(cache.get("b"), 2)


if __name__ == "__main__":
    unittest.main()
